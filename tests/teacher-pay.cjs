const {execFileSync} = require('node:child_process');
const {chromium} = require('../.test-tools/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const {randomUUID} = require('node:crypto');
const project = 'madrassa-integration-teacher-pay-'+Date.now().toString(36);
const base = 'http://localhost:18190';
const env = {...process.env,COMPOSE_PROJECT_NAME:project,COMPOSE_FILE:['compose.yaml','tests/compose.test.yaml'].join(path.delimiter),APP_PORT:'18190',APP_URL:base,DB_DATABASE:'teacher_pay_test',DB_PASSWORD:'local-test-only'};
const compose = args=>execFileSync('docker-compose',args,{env,encoding:'utf8',stdio:['ignore','pipe','pipe']});
const fixture = action=>JSON.parse(compose(['run','--rm','--no-deps','-T','--entrypoint','php','-v','./tests:/integration:ro','app','/integration/teacher-pay-fixture.php',action]));
(async()=>{
    let browser;
    try {
        compose(['up','-d','--no-build']);
        let ready=false;
        for(let i=0;i<60;i++){try{if((await fetch(base+'/school-api/csrf')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,500));}
        assert.ok(ready,'Payment migrations applied');
        const data=fixture('setup');
        browser=await chromium.launch({channel:'msedge',headless:true});
        const admin=await browser.newPage();
        const teacher=await browser.newPage();
        const other=await browser.newPage();
        const errors=[]; for(const page of [admin,teacher,other]) page.on('pageerror',e=>errors.push(e.message));
        const login=async(page,user,isAdmin=false)=>{
            await page.goto(base+(isAdmin?'/admin/login':'/enseignant/login'));
            await page.locator('input[type=email]').fill(user.email);
            await page.locator('input[type=password]').fill(user.password);
            await page.locator('button[type=submit]').click();
            await page.waitForURL(isAdmin?'**/admin/dashboard':'**/enseignant');
        };
        await login(admin,data.admin,true); await login(teacher,data.teachers[0]); await login(other,data.teachers[1]);
        const tokens=new Map();
        for(const page of [admin,teacher,other]) tokens.set(page,(await (await page.request.get(base+'/school-api/csrf')).json()).csrf_token);
        const send=(page,url,payload)=>page.request.post(url,{headers:{Accept:'application/json','X-CSRF-TOKEN':tokens.get(page)},data:payload,maxRedirects:0});
        const adminUrl=base+'/remunerations/'+data.tenant;
        const teacherUrl=base+'/enseignant/remuneration';
        const api=base+'/school-api/v1/tenants/'+data.tenant;
        assert.equal((await teacher.request.get(adminUrl,{headers:{Accept:'application/json'}})).status(),403,'Teacher cannot read other payrolls');
        await teacher.goto(teacherUrl+'?month=2026-09'); await teacher.getByRole('heading',{name:'Mes heures et ma rémunération'}).waitFor();
        const contract=async(index,basis,rate)=>{
            const r=await send(admin,adminUrl+'/contrats',{staff_id:data.teachers[index].staff,starts_on:'2026-09-01',basis,rate});
            assert.equal(r.status(),302,await r.text());
            const rows=(await (await admin.request.get(api+'/contracts')).json()).data;
            return rows.find(c=>c.staff_id===data.teachers[index].staff);
        };
        const first=await contract(0,'hourly','1200'); const second=await contract(1,'monthly','20000');
        assert.equal((await send(admin,adminUrl+'/contrats',{staff_id:data.teachers[0].staff,starts_on:'2026-09-15',basis:'hourly',rate:'1000'})).status(),409,'Overlapping contracts denied');
        const declaration={contract_id:first.id,worked_on:'2026-09-01',minutes:150};
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,contract_id:second.id})).status(),404,'Cannot declare another teacher hours');
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,worked_on:'2099-01-01'})).status(),422,'Future worked hours denied');
        assert.equal((await send(teacher,teacherUrl+'/heures',declaration)).status(),302);
        const log=async()=>{
            await teacher.goto(teacherUrl+'?month=2026-09');
            const form=teacher.locator('form').filter({has:teacher.locator('input[name=version]')}).first();
            return {version:await form.locator('[name=version]').inputValue()};
        };
        const oldVersion=await log();
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,...oldVersion,minutes:180})).status(),302);
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,...oldVersion,minutes:160})).status(),422,'Stale correction denied');
        const calculate=(index=0)=>send(admin,adminUrl+'/calculer',{staff_id:data.teachers[index].staff,month:'2026-09'});
        assert.equal((await calculate()).status(),422,'Pending hours block payroll');
        const review=async(decision)=>{
            await admin.goto(adminUrl+'?staff='+data.teachers[0].staff+'&month=2026-09');
            const form=admin.locator('.pay-review').first();
            const action=await form.getAttribute('action');
            return send(admin,action,{version:await form.locator('[name=version]').inputValue(),reason:'Review integration',decision});
        };
        assert.equal((await review('reject')).status(),302);
        const rejectedVersion=await log();
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,...rejectedVersion})).status(),302,'Rejected hours can be corrected');
        assert.equal((await review('validate')).status(),302);
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,...rejectedVersion,minutes:200})).status(),422,'Validated hours frozen');
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,worked_on:'2026-09-02',minutes:75})).status(),302);
        assert.equal((await calculate()).status(),422,'New pending hours block closing');
        assert.equal((await review('reject')).status(),302,'Rejected hours excluded from pay');
        assert.equal((await calculate()).status(),302);
        assert.equal((await calculate()).status(),302,'Monthly payroll replay');
        assert.equal((await calculate(1)).status(),302,'Monthly remuneration without hourly logs');
        assert.equal((await send(teacher,teacherUrl+'/heures',{...declaration,worked_on:'2026-09-02'})).status(),422,'Closed month frozen');
        const runs=(await (await admin.request.get(api+'/payroll_runs')).json()).data;
        const run=runs.find(r=>r.staff_id===data.teachers[0].staff);
        assert.equal(Number(run.amount_minor),300000,'150 minutes x 1200 DA per hour');
        const expenseRows=(await (await admin.request.get(api+'/expenses')).json()).data;
        assert.equal(expenseRows.filter(e=>e.payroll_id===run.id).length,1,'One expense per remuneration');
        const paymentUrl=adminUrl+'/versements/'+run.id;
        const payload={amount:'1000',paid_on:'2026-10-02',method:'bank',reference:'PAY-TEST',idempotency_key:randomUUID()};
        assert.equal((await send(teacher,paymentUrl,payload)).status(),403,'Teacher cannot record payments');
        await admin.goto(adminUrl+'?staff='+data.teachers[0].staff+'&month=2026-09');
        const payForm=admin.locator('form').filter({has:admin.locator('input[name=amount]')});
        payload.idempotency_key=await payForm.locator('[name=idempotency_key]').inputValue();
        for(const field of ['amount','paid_on','reference']) await payForm.locator('[name='+field+']').fill(payload[field]);
        await payForm.locator('[name=method]').selectOption(payload.method);
        await payForm.getByRole('button',{name:'Enregistrer le versement',exact:true}).click();
        await admin.getByText('Versement enregistré. Le solde a été mis à jour.',{exact:true}).waitFor();
        assert.equal((await send(admin,paymentUrl,payload)).status(),302,'Payment retry creates no duplicate');
        assert.equal((await send(admin,paymentUrl,{...payload,amount:'1001'})).status(),409,'Idempotency key content mismatch');
        await teacher.goto(teacherUrl+'?month=2026-09');
        assert.ok((await teacher.locator('[data-pay-balance]').innerText()).includes('2 000,00'));
        await teacher.getByText('Partiellement payé',{exact:true}).waitFor();
        const concurrent=await Promise.all([1,2].map(()=>send(admin,paymentUrl,{...payload,amount:'1500',idempotency_key:randomUUID()})));
        assert.deepEqual(concurrent.map(r=>r.status()).sort(),[302,409],'Concurrent payments cannot exceed balance');
        assert.equal((await send(admin,paymentUrl,{...payload,amount:'501',idempotency_key:randomUUID()})).status(),409,'Overpayment blocked');
        assert.equal((await send(admin,paymentUrl,{...payload,amount:'500',idempotency_key:randomUUID()})).status(),302);
        await teacher.goto(teacherUrl+'?month=2026-09'); await teacher.getByText('Payé',{exact:true}).waitFor();
        assert.ok((await teacher.locator('[data-pay-paid]').innerText()).includes('3 000,00'));
        assert.equal(await teacher.getByRole('link',{name:'Imprimer le reçu',exact:true}).count(),3);
        const receipt=await teacher.getByRole('link',{name:'Imprimer le reçu',exact:true}).first().getAttribute('href');
        assert.equal((await other.request.get(receipt,{headers:{Accept:'application/json'}})).status(),404,'Cannot read another teacher receipt');
        await other.goto(teacherUrl+'?month=2026-09');
        assert.ok((await other.locator('[data-pay-due]').innerText()).includes('20 000,00'));
        assert.ok(!(await other.content()).includes('PAY-TEST'),'Payment history stays private');
        fs.mkdirSync('tests/artifacts',{recursive:true});
        await admin.goto(adminUrl+'?staff='+data.teachers[0].staff+'&month=2026-09');
        await admin.screenshot({path:'tests/artifacts/teacher-pay-admin.png',fullPage:true});
        await teacher.screenshot({path:'tests/artifacts/teacher-pay-desktop.png',fullPage:true});
        await teacher.setViewportSize({width:390,height:844});
        await teacher.screenshot({path:'tests/artifacts/teacher-pay-mobile.png',fullPage:true});
        assert.equal(await teacher.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Mobile page fits viewport');
        await teacher.goto(receipt); await teacher.locator('.sheet').waitFor();
        await teacher.pdf({path:'tests/artifacts/teacher-payment-receipt.pdf',format:'A4',preferCSSPageSize:true});
        fixture('disable');
        assert.equal((await teacher.request.get(teacherUrl,{headers:{Accept:'application/json'}})).status(),403,'Disabled teacher loses access');
        assert.deepEqual(errors,[]);
        console.log('PASS teacher payment workflow: declarations, stale edits, review, contracts, hourly/monthly calculation, pending/closed hours, idempotency, partial/concurrent payments, overpayment prevention, privacy, receipt, mobile, revocation.');
    } finally {
        if(browser) await browser.close();
        if(!project.startsWith('madrassa-integration-teacher-pay-')) throw new Error('Unexpected project');
        compose(['down','-v','--remove-orphans']);
    }
})().catch(e=>{console.error(e);process.exitCode=1;});
